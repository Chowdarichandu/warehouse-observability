DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='obs_app') THEN CREATE ROLE obs_app NOLOGIN; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='obs_ro') THEN CREATE ROLE obs_ro NOLOGIN; END IF;
END $$;
GRANT USAGE ON SCHEMA obs TO obs_app,obs_ro;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA obs TO obs_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA obs TO obs_app;
GRANT SELECT ON ALL TABLES IN SCHEMA obs TO obs_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA obs GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO obs_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA obs GRANT SELECT ON TABLES TO obs_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA obs GRANT USAGE,SELECT ON SEQUENCES TO obs_app;
